package com.example.hcmanager

object TeamShortName {
    fun get(fullName: String): String = when (fullName) {
        "СКА" -> "СКА"
        "ЦСКА" -> "ЦСКА"
        "Динамо Москва" -> "ДИН"
        "Спартак" -> "СПА"
        "Локомотив" -> "ЛОК"
        "Северсталь" -> "СЕВ"
        "Торпедо" -> "ТОР"
        "Динамо Минск" -> "ДМН"
        "ХК Сочи" -> "СОЧИ"
        "Лада" -> "ЛАДА"
        "Шанхайские драконы" -> "ШДР"

        "Металлург" -> "ММГ"
        "Авангард" -> "АВГ"
        "Ак Барс" -> "АКБ"
        "Салават Юлаев" -> "СЮЛ"
        "Автомобилист" -> "АВТ"
        "Трактор" -> "ТРА"
        "Сибирь" -> "СИБ"
        "Адмирал" -> "АДМ"
        "Амур" -> "АМУР"
        "Барыс" -> "БАР"
        "Нефтехимик" -> "НХК"

        else -> fullName.take(3).uppercase() // Запасной вариант
    }
}